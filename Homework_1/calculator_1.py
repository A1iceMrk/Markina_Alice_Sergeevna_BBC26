n1 = float(input('Введите первое число: '))
op = input('Введите операцию (+, -, *, /): ')
n2 = float(input('Введите второе число: '))

if op == '+':
    print('Результат: ', n1 + n2)
elif op == '-':
    print('Результат: ', n1 - n2)
elif op == '*':
    print('Результат: ', n1 * n2)
elif op == '/':
    if n2 != 0:
        print('Результат: ', n1 / n2)
    else:
        print('Ошибка. Деление на ноль невозможно')
else:
    print('Неизвестная операця')